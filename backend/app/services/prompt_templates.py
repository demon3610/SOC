    "* be safe to initialize more than once\n"
    "* never throw an exception that can break the website\n"
    "\n"
    "The ingestion endpoint is:\n"
    "\n"
    "`{server_url}/ingest/event`\n"
    "\n"
    "Send requests with:\n"
    "\n"
    "```http\n"
    "Content-Type: application/json\n"
    "X-API-Key: {api_key}\n"
    "```\n"
    "\n"
    "## 4. Page-view telemetry\n"
    "\n"
    "On the initial application load, send:\n"
    "\n"
    "```json\n"
    "{{\n"
    "  \"event_type\": \"page_view\",\n"
    "  \"raw\": {{\n"
    "    \"url\": \"window.location.href\",\n"
    "    \"referrer\": \"document.referrer\",\n"
    "    \"user_agent\": \"navigator.userAgent\"\n"
    "  }}\n"
    "}}\n"
    "```\n"
    "\n"
    "Use the actual browser values, not the literal strings shown above.\n"
    "\n"
    "For SPA applications, also capture client-side route changes if the framework provides a reliable routing/navigation hook. Do not reload the page solely to generate telemetry.\n"
