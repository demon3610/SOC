    "You are the site's engineer: wire this in the way you would wire any other\n"
    "monitoring dependency, and confirm the work with a summary of what changed.\n"
    "\n"
    "================================================================================\n"
    "1. WHAT TO BUILD\n"
    "================================================================================\n"
    "Create a small monitoring module and initialize it exactly once at the app's\n"
