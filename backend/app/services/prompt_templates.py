    "\n"
    "  1. Create a new file at the appropriate location for this stack, e.g.:\n"
    "       - JS/TS frontend (React, Vue, Svelte, plain JS): src/lib/soc-monitor.js\n"
    "       - Next.js: lib/soc-monitor.js, initialized in src/app/layout.tsx or _app.tsx\n"
    "       - Nuxt: plugins/soc-monitor.client.js\n"
    "       - Server-rendered or backend project: a small request middleware file\n"
    "     If the repo has both a frontend and a backend, ask me which one to target\n"
    "     before writing code.\n"
    "  2. The module reads two config values from this project's existing env\n"
    "     convention (VITE_*, NEXT_PUBLIC_*, or plain .env) and nothing else:\n"
    "       - SOC_SERVER_URL — the SOC backend base URL\n"
    "       - SOC_API_KEY     — the website integration API key\n"
    "     Do NOT hardcode a host, IP, or domain anywhere in the committed source.\n"
    "     The host must always come from the env var with no baked-in fallback.\n"
    "  3. The module posts events to the SOC ingest endpoint (contract in section 3).\n"
    "  4. The module attaches a global error listener (window.onerror + the\n"
    "     unhandledrejection event) and reports JS errors the same way.\n"
    "  5. Never include a project ID anywhere — the API key alone identifies the\n"
    "     project. The backend rejects nothing for this, but the key IS the tenant.\n"
    "  6. Import and initialize the module once at the app entry point (main.jsx /\n"
