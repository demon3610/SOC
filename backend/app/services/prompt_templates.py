    "\n"
    "Unless the repository contains an explicit SOC API contract proving that `/ingest/event` accepts arrays, send events individually with a bounded queue and throttled flushing.\n"
    "\n"
    "The queue must have a reasonable maximum size so a broken application cannot create unlimited telemetry memory usage.\n"
    "\n"
    "## 7. Missing configuration\n"
    "\n"
    "If either required environment variable is missing or empty:\n"
    "\n"
    "* do not make any SOC request\n"
