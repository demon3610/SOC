    "* unavailable\n"
    "* unreachable\n"
    "* incorrectly configured\n"
    "* blocked by CORS\n"
    "* returning an error\n"
    "* timing out\n"
    "\n"
    "the website itself must continue working normally.\n"
    "\n"
    "Telemetry failures must not create uncaught exceptions.\n"
    "\n"
    "Use a reasonable request timeout where supported.\n"
    "\n"
    "For browser telemetry, consider `keepalive` for small event requests where supported.\n"
    "\n"
    "## 9. Initialization\n"
    "\n"
    "Initialize the SOC module exactly once at the application's real entry point.\n"
    "\n"
    "Examples:\n"
    "\n"
    "* Vite/React → `main.jsx` / `main.tsx`\n"
    "* Next.js → appropriate root client boundary/layout\n"
    "* React Router → application bootstrap/root\n"
    "* Vue → `main.js` / `main.ts`\n"
    "* other frameworks → their actual application bootstrap point\n"
    "\n"
    "Do not add the initialization separately to every page/component.\n"
    "\n"
    "Make initialization idempotent so accidental repeated calls do not register duplicate global listeners.\n"
    "\n"
    "## 10. Security constraints\n"
    "\n"
    "Do not send:\n"
    "\n"
    "* project IDs\n"
    "* hardcoded SOC hosts\n"
    "* cookies\n"
    "* authorization tokens from the website\n"
    "* passwords\n"
    "* form contents\n"
    "* arbitrary page/application secrets\n"
    "\n"
    "The SOC API key is the only project-identifying credential used by this integration.\n"
    "\n"
    "If the implementation is browser-side and the framework exposes the API key to users, clearly note that the key is necessarily client-visible. If the SOC API key must remain secret, use the project's server/backend as the telemetry proxy instead.\n"
    "\n"
    "## 11. Verification\n"
    "\n"
    "After implementing the integration, inspect the resulting source and verify:\n"
    "\n"
    "1. The SOC module exists.\n"
    "2. It is imported/initialized from the real application entry point.\n"
    "3. The page-view event is generated.\n"
    "4. `window.onerror` is registered.\n"
    "5. `unhandledrejection` is registered.\n"
    "6. Events use `X-API-Key`.\n"
    "7. No project ID is sent.\n"
    "8. Missing configuration produces the required single warning.\n"
    "9. Network errors cannot break the application.\n"
    "10. Error bursts are throttled/buffered.\n"
    "11. The endpoint is constructed only from the configured environment variable.\n"
    "12. No hardcoded `localhost`, `127.0.0.1`, private IP, public IP, or SOC domain exists in source code.\n"
